"""Level-2 reduce: per-video summaries -> cross-video report and combined mindmap.

Per-video source IDs (S0007) are mechanically rewritten to V{nn}.S{nnnn} before
the LLM sees them; a run-wide resolution table maps them back to
(video_id, start_seconds) so deep links are always generated by code.
"""

from __future__ import annotations

import json
import re
from typing import Any

from .chunking import clean_text
from .llm import LlmConfig, call_llm_json, log
from .mindmap import clean_label, normalize_mindmap, normalize_source_ids
from .models import VideoResult
from .prompts_io import render_template

PLAIN_SOURCE_ID_RE = re.compile(r"\bS\d{4,}\b")


def video_prefix(index: int) -> str:
    return f"V{index:02d}"


def rewrite_source_ids(value: Any, index: int) -> Any:
    """Recursively rewrite S0007 -> V{nn}.S0007 in every source_ids list."""
    prefix = video_prefix(index)
    if isinstance(value, dict):
        out = {}
        for key, item in value.items():
            if key == "source_ids" and isinstance(item, list):
                out[key] = [
                    PLAIN_SOURCE_ID_RE.sub(lambda m: f"{prefix}.{m.group(0)}", str(sid))
                    if not str(sid).startswith("V")
                    else str(sid)
                    for sid in item
                ]
            else:
                out[key] = rewrite_source_ids(item, index)
        return out
    if isinstance(value, list):
        return [rewrite_source_ids(item, index) for item in value]
    return value


def build_resolution_table(results: list[VideoResult]) -> dict[str, tuple[str, float]]:
    """Map both V{nn}.S{nnnn} and (per-video local use) S{nnnn} keys to
    (video_id, start_seconds)."""
    table: dict[str, tuple[str, float]] = {}
    for result in results:
        prefix = video_prefix(result.index)
        for segment in result.segments:
            if segment.source_id and segment.start is not None:
                table[f"{prefix}.{segment.source_id}"] = (result.meta.video_id, float(segment.start))
    return table


def make_link_resolver(table: dict[str, tuple[str, float]]):
    def resolver(source_ids: list[str]) -> tuple[float, str] | None:
        for source_id in source_ids:
            hit = table.get(source_id)
            if hit:
                video_id, start = hit
                return start, f"https://www.youtube.com/watch?v={video_id}&t={int(start)}s"
        return None

    return resolver


def quote_id(video_index: int, position: int) -> str:
    return f"{video_prefix(video_index)}.Q{position}"


def build_quote_pool(results: list[VideoResult]) -> tuple[list[dict[str, Any]], dict[str, dict[str, Any]]]:
    """Every transcript-verified quote across the run, addressed by V{nn}.Q{n}. The
    synthesis LLM selects by id; the lookup lets code reject anything it invents."""
    pool: list[dict[str, Any]] = []
    lookup: dict[str, dict[str, Any]] = {}
    for result in results:
        for position, quote in enumerate((result.summary or {}).get("quotes") or [], 1):
            qid = quote_id(result.index, position)
            entry = {
                "id": qid,
                "video_index": result.index,
                "speaker": quote.get("speaker") or "",
                "quote": quote["quote"],
                "why": quote.get("why") or "",
            }
            pool.append(entry)
            lookup[qid] = {
                **entry,
                "video_id": result.meta.video_id,
                "source_ids": [f"{video_prefix(result.index)}.{sid}" for sid in quote.get("source_ids") or []],
            }
    return pool, lookup


def normalize_report(data: dict[str, Any], insights_lookup: dict | None = None,
                     quotes_lookup: dict | None = None) -> dict[str, Any]:
    themes: list[dict[str, Any]] = []
    for theme in data.get("common_themes") or []:
        if not isinstance(theme, dict):
            continue
        name = clean_label(theme.get("theme") or theme.get("name") or "")
        if not name:
            continue
        themes.append(
            {
                "theme": name,
                "explanation": clean_text(str(theme.get("explanation") or "")),
                "source_ids": normalize_source_ids(theme.get("source_ids") or []),
            }
        )

    disagreements: list[dict[str, Any]] = []
    for item in data.get("disagreements") or []:
        if not isinstance(item, dict):
            continue
        topic = clean_label(item.get("topic") or "")
        positions = []
        for pos in item.get("positions") or []:
            if not isinstance(pos, dict):
                continue
            try:
                vindex = int(pos.get("video_index") or 0)
            except (TypeError, ValueError):
                vindex = 0
            text = clean_text(str(pos.get("position") or ""))
            if text:
                positions.append(
                    {
                        "video_index": vindex,
                        "position": text,
                        "source_ids": normalize_source_ids(pos.get("source_ids") or []),
                    }
                )
        if topic and positions:
            disagreements.append({"topic": topic, "positions": positions})

    recommendations: list[dict[str, Any]] = []
    for rec in data.get("watch_recommendations") or []:
        if not isinstance(rec, dict):
            continue
        try:
            vindex = int(rec.get("video_index") or 0)
        except (TypeError, ValueError):
            continue
        if vindex <= 0:
            continue
        try:
            rank = int(rec.get("rank") or len(recommendations) + 1)
        except (TypeError, ValueError):
            rank = len(recommendations) + 1
        recommendations.append(
            {
                "video_index": vindex,
                "rank": rank,
                "verdict": clean_text(str(rec.get("verdict") or "")),
                "why": clean_text(str(rec.get("why") or "")),
            }
        )
    recommendations.sort(key=lambda r: r["rank"])

    community_signal: list[dict[str, Any]] = []
    if insights_lookup:
        for item in data.get("community_signal") or []:
            if not isinstance(item, dict):
                continue
            observation = clean_text(str(item.get("observation") or ""))
            refs = []
            for ref in item.get("refs") or []:
                if not isinstance(ref, dict):
                    continue
                try:
                    vindex = int(ref.get("video_index") or 0)
                except (TypeError, ValueError):
                    continue
                insight = insights_lookup.get((vindex, str(ref.get("comment_id") or "")))
                if insight is None:
                    continue  # invented or mismatched ref - drop
                refs.append(
                    {
                        "video_index": vindex,
                        "comment_id": insight["comment_id"],
                        "video_id": insight["video_id"],
                        "author": insight.get("author") or "unknown",
                        "like_count": insight.get("like_count") or 0,
                    }
                )
            if observation and refs:
                community_signal.append({"observation": observation, "refs": refs})

    best_quotes: list[dict[str, Any]] = []
    if quotes_lookup:
        seen_ids: set[str] = set()
        for item in data.get("best_quotes") or []:
            if isinstance(item, str):
                item = {"id": item}
            if not isinstance(item, dict):
                continue
            qid = clean_text(str(item.get("id") or item.get("quote_id") or "")).upper()
            entry = quotes_lookup.get(qid)
            if entry is None or qid in seen_ids:
                continue  # invented, mismatched, or repeated id - drop
            seen_ids.add(qid)
            best_quotes.append({**entry, "why": clean_text(str(item.get("why") or entry.get("why") or ""))[:200]})
            if len(best_quotes) >= 12:
                break

    return {
        "overview": clean_text(str(data.get("overview") or "")),
        "common_themes": themes,
        "disagreements": disagreements,
        "watch_recommendations": recommendations,
        "community_signal": community_signal,
        "best_quotes": best_quotes,
    }


def build_roster(results: list[VideoResult]) -> list[dict[str, Any]]:
    roster = []
    for result in results:
        verdict = (result.summary or {}).get("watch_verdict") or {}
        roster.append(
            {
                "video_index": result.index,
                "video_id": result.meta.video_id,
                "title": result.meta.title,
                "channel": result.meta.channel,
                "duration_seconds": result.meta.duration,
                "view_count": result.meta.view_count,
                "watch_verdict": verdict,
            }
        )
    return roster


def synthesize(
    client: Any,
    llm_config: LlmConfig,
    summarized: list[VideoResult],
    query: str,
    prompts: dict[str, str],
    api_mode: str = "auto",
    max_output_tokens: int = 16000,
) -> tuple[dict[str, Any], dict[str, Any]]:
    """Run the two level-2 calls. Returns (report_json, mindmap_json)."""
    rewritten = [
        rewrite_source_ids(result.summary, result.index) for result in summarized
    ]
    roster = build_roster(summarized)
    community = [
        {
            "video_index": result.index,
            "insights": [
                {key: ins.get(key) for key in ("comment_id", "type", "insight", "like_count", "is_uploader")}
                for ins in result.comment_insights
            ],
        }
        for result in summarized
        if result.comment_insights
    ]
    insights_lookup = {
        (result.index, ins["comment_id"]): {**ins, "video_id": result.meta.video_id}
        for result in summarized
        for ins in result.comment_insights
    }
    quote_pool, quotes_lookup = build_quote_pool(summarized)
    common = {
        "query": query,
        "video_count": str(len(summarized)),
        "roster_json": json.dumps(roster, ensure_ascii=False, indent=2),
        "summaries_json": json.dumps(rewritten, ensure_ascii=False, indent=2),
        "community_json": json.dumps(community, ensure_ascii=False, indent=2),
        "quotes_json": json.dumps(quote_pool, ensure_ascii=False, indent=2),
    }

    log(f"synthesizing cross-video report from {len(summarized)} summaries")
    report_data = call_llm_json(
        client, llm_config, prompts["synthesis_system"],
        render_template(prompts["synthesis_user"], common),
        label="synthesis", api_mode=api_mode, max_output_tokens=max_output_tokens,
    )
    report = normalize_report(report_data, insights_lookup, quotes_lookup)

    log("building combined mindmap")
    mindmap_data = call_llm_json(
        client, llm_config, prompts["crossmap_system"],
        render_template(prompts["crossmap_user"], common),
        label="crossmap", api_mode=api_mode, max_output_tokens=max_output_tokens,
    )
    mindmap = normalize_mindmap(mindmap_data, default_title=f"YouTube: {query}")
    return report, mindmap
